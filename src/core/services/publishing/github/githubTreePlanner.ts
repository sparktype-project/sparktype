/**
 * Plans the tree a deployment submits to GitHub.
 *
 * Two rules shape the plan:
 *
 * 1. **Binary assets cannot be inlined.** Tree entries have no `encoding` field, so bytes in a
 *    tree entry's `content` are committed as literal text. Inline entries are therefore text
 *    only; binary content is marked for the blob API (see `githubBlobUploader.ts`).
 * 2. **Obsolete generated paths are deleted explicitly.** A tree is created with `base_tree`, and
 *    GitHub *retains* every base-tree path the new tree does not mention. A deleted, renamed or
 *    unpublished page would stay live forever unless its path is submitted with `sha: null`.
 *
 * Deletion is only safe against paths this site generated in a previous deployment of the same
 * repository and branch. When no such history exists the plan deletes nothing: a repository with
 * unrelated files (a user's README, their own branches of content) must never be mass-deleted
 * because Sparktype has no record of what it once wrote.
 */

export interface DeploymentPlanInput {
  files: Map<string, string | Uint8Array>;
  /**
   * Paths generated by the previous deployment into this repository and branch, or `null` when
   * there is no recorded history (a repository predating path tracking, a new site, or a
   * changed repository/branch). `null` disables deletions.
   */
  previousPaths: readonly string[] | null;
  /** Deletions need a base tree to act on; a root commit has nothing to remove. */
  hasBaseTree: boolean;
}

export type PlannedEntry =
  | { kind: 'text'; path: string; content: string }
  | { kind: 'binary'; path: string; content: Uint8Array }
  | { kind: 'delete'; path: string };

export interface DeploymentPlan {
  entries: PlannedEntry[];
  /** Every path this deployment generates, to be recorded for the next deployment. */
  generatedPaths: string[];
  /** Obsolete tracked paths this deployment asks GitHub to delete. */
  deletedPaths: string[];
}

export function planDeployment(input: DeploymentPlanInput): DeploymentPlan {
  const entries: PlannedEntry[] = [];

  for (const [path, content] of input.files) {
    entries.push(
      typeof content === 'string'
        ? { kind: 'text', path, content }
        : { kind: 'binary', path, content },
    );
  }

  const deletedPaths =
    input.previousPaths !== null && input.hasBaseTree
      ? input.previousPaths.filter((path) => !input.files.has(path)).sort()
      : [];

  for (const path of deletedPaths) {
    entries.push({ kind: 'delete', path });
  }

  return {
    entries,
    generatedPaths: [...input.files.keys()].sort(),
    deletedPaths,
  };
}
